def accepted_lines() -> set[str]:
    lines: set[str] = set()
    for entries in STEPS.values():
        for (key, kind), items in entries.items():
            for scope in (FILES[key], PROJECT):
                for item in items:
                    if kind == "endpoint":
                        lines.add(f"{scope}: {item}")
                    elif kind == "perform added":
                        lines.add(f"{scope}: {item} performTargetId None -> {perform_target(item)!r}")
                    elif kind == "perform removed":
                        lines.add(f"{scope}: {item} performTargetId {perform_target(item)!r} -> None")
                    else:
                        lines.add(f"{scope}: {kind} {item!r}")
    return lines
