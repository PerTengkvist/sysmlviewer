def perform_target(perform_id: str) -> str:
    """`<owner>::perform_<a>_<b>` -> the step it names.

    A function node performs `flow.step` of its function: `<function>::<flow>::<step>`. An
    actor performs a step of its use case: `<use case>::<step>`.
    """
    owner, local = perform_id.rsplit("::perform_", 1)
    container = owner.rsplit("::", 1)[0]
    return f"{container}::{local.replace('_', '::')}"


